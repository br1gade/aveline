/**
 * Writes `src/api/public-paths.ts`, the operations `backend/openapi.json` declares public with
 * `security: []` (FR-2), as a type over the generated `paths`. `createPublicApi` is typed with it,
 * so a public page calling a signed-in operation fails the typecheck. Run by `npm run api:generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const METHODS = ['get', 'put', 'post', 'delete', 'patch'];
const SPEC = new URL('../../backend/openapi.json', import.meta.url);
const OUT = new URL('../src/api/public-paths.ts', import.meta.url);

/** Each path's public methods; an operation that declares no `security` is not public. */
export function publicOperations(spec) {
  const operations = {};
  for (const [path, item] of Object.entries(spec.paths)) {
    const methods = METHODS.filter((method) => {
      const security = item[method]?.security;
      return Array.isArray(security) && security.length === 0;
    });
    if (methods.length > 0) operations[path] = methods;
  }
  return operations;
}

export function publicPathsSource(spec) {
  const rows = Object.entries(publicOperations(spec)).map(
    ([path, methods]) =>
      `  '${path}': Pick<paths['${path}'], 'parameters' | ${methods.map((m) => `'${m}'`).join(' | ')}>;`,
  );
  return [
    '// Generated by scripts/public-paths.mjs from backend/openapi.json (FR-2). Do not edit.',
    "import type { paths } from './schema';",
    '',
    'export interface PublicPaths {',
    ...rows,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, publicPathsSource(JSON.parse(readFileSync(SPEC, 'utf8'))));
}
